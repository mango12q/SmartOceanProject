def nearest_value(arr, la_grid, lo_grid, lat, lon):
    """Return value at grid point nearest to (lat,lon)."""
    d = (la_grid - lat) ** 2 + (lo_grid - lon) ** 2
    idx = int(d.argmin())
    i, j = np.unravel_index(idx, d.shape)
    return float(arr[i, j])


def main():
    ds = xr.open_dataset(WRF_FILE)
    u = ds["U10"].values
    v = ds["V10"].values
    ps = ds["PSFC"].values
    la = ds["XLAT"].values
    lo = ds["XLONG"].values

    # Track tail via vorticity from t=233
    tail = {}
    py, px = 21.39, 109.56
    for k in range(234, 250):
        uu = u[k]
        vv = v[k]
        dudy, dudx = np.gradient(uu, axis=(0, 1))
        dvdy, dvdx = np.gradient(vv, axis=(0, 1))
        vort = dvdx - dudy
        mask = (la[k] >= 20) & (la[k] <= 23) & (lo[k] >= 107) & (lo[k] <= 111)
        vz = np.where(mask, vort, -1e9)
        pos = int(vz.reshape(-1).argmax())
        i = pos // vz.shape[1]
        j = pos % vz.shape[1]
        py = float(la[k][i, j])
        px = float(lo[k][i, j])
        p = nearest_value(ps[k], la[k], lo[k], py, px)
        w = np.hypot(uu[i, j], vv[i, j])
        tail[k] = [py, px, int(p), round(float(w), 1)]
        print(f"tail {k}: ({py:.2f},{px:.2f}) psfc={int(p)} wind={w:.1f}")

    # Fill missing t in B segment (125, 185, 229, 232) by linear interpolation
    keys = sorted(EXISTING.keys())
    full = dict(EXISTING)
    for t in range(105, 250):
        if t in full:
            continue
        # find prev & next
        prevs = [x for x in keys if x < t]
        nexts = [x for x in keys if x > t and x <= 233]
        if t >= 234:
            continue  # handled by tail
        if not prevs or not nexts:
            continue
        p0 = EXISTING[max(prevs)]
        p1 = EXISTING[min(nexts)]
        frac = (t - max(prevs)) / (min(nexts) - max(prevs))
        lat = p0[0] + (p1[0] - p0[0]) * frac
        lon = p0[1] + (p1[1] - p0[1]) * frac
        psfc = int(p0[2] + (p1[2] - p0[2]) * frac)
        wind = round(p0[3] + (p1[3] - p0[3]) * frac, 1)
        full[t] = [round(lat, 2), round(lon, 2), psfc, wind]
        print(f"interp {t}: ({lat:.2f},{lon:.2f})")

    # Merge tail
    for t, v in tail.items():
        full[t] = v

    # Build final array sorted by t
    out = []
    for t in sorted(full):
        lat, lon, psfc, wind = full[t]
        out.append({"t": t, "lat": lat, "lon": lon, "psfc": psfc, "wind": wind})

    print("\nTotal points:", len(out))
    print("t range:", out[0]["t"], "~", out[-1]["t"])
    print(json.dumps(out))


if __name__ == "__main__":
    main()
